/*
* Color strobe effect function 
* Is activated as long as corresponding button is pressed
* Output color as strobe effect corresponding to RGB sliders on strobe only
* Follows global brightness and frequency settings
*/
void flash_color_linked()
{

	_Bool toogle = 1;
	
	uint8_t i = 0;
	
	int16_t output_red = 0;
	int16_t output_green = 0;
	int16_t output_blue = 0;
	
	switchdmxinput(PA_INTERNAL);

	while(1)
	{
		if(DMX_data_valid){
			dma_bytecopy(&dmx_buffer[0],&dmx_output[0],512);
			while (DMA.CH1.CTRLA & DMA_CH_TRFREQ_bm);
			DMA.CH1.CTRLA |= DMA_CH_TRFREQ_bm;
			while(!DMA_complete);
			DMX_data_valid = 0;
			DMA_complete = 0;
		}
		if(toogle)
		{
		output_red = (global_red-(127-global_brightness))*2;
		output_green = (global_green-(127-global_brightness))*2;
		output_blue = (global_blue-(127-global_brightness))*2;
		
			if (output_red>0)
			{
				dmx_output[flash_red_ch]=output_red;
			}
			else
			{
				dmx_output[flash_red_ch]=0;
			}
			
			if (output_green>0)
			{
				dmx_output[flash_green_ch]=output_green;
			}
			else
			{
				dmx_output[flash_green_ch]=0;
			}
			
			if (output_blue>0)
			{
				dmx_output[flash_blue_ch]=output_blue;
			}
			else
			{
				dmx_output[flash_blue_ch]=0;
			}
		toogle = 0;
		}
		
		else{
			dmx_output[flash_red_ch] = 0x00;
			dmx_output[flash_blue_ch] = 0x00;
			dmx_output[flash_green_ch] = 0x00;
			toogle = 1;
		}
		
		start_dmx(&dmx_output[0],512);
		_delay_ms(23);
		for (i=0;i<(127-global_frequency);i++)
		{
			_delay_ms(1);
		}

		
		if (!(PORTD.IN & (1<<6)))						//Disable function as soon as button is released by checking for SBUF signal from display
		{
			switchdmxinput(global_pa_source);
			break;
		}
	}
	switchdmxinput(global_pa_source);	
}



