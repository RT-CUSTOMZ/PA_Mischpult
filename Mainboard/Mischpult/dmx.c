/*
* DMX routing switch function
* Is activated along with corresponding function
* Sets I/O ports to control signal distribution of DMX via SP3T switches
*/
void switchdmxinput(uint8_t source)
{
	switch(source)
	{
		case PA_INTERNAL:
		PORTE.OUTSET = PIN6_bm;												//Pin E6 as High
		PORTE.OUTCLR = PIN7_bm;												//Pin E7 as Low
		break;
		
		case PA_EXTERNAL:
		PORTE.OUTCLR = PIN6_bm;												//Pin E6 as Low
		PORTE.OUTSET = PIN7_bm;												//Pin E7 as High
		break;
		
		case PA_USB:
		PORTE.OUTSET = PIN6_bm;												//Pin E6 as High
		PORTE.OUTSET = PIN7_bm;												//Pin E7 as High
		break;
		
		case STRB_INTERNAL:
		PORTE.OUTSET = PIN4_bm;												//Pin E4 as High
		PORTE.OUTSET = PIN5_bm;												//Pin E5 as High
		break;
		
		case STRB_EXTERNAL:
		PORTE.OUTSET = PIN4_bm;												//Pin E4 as High
		PORTE.OUTSET = PIN5_bm;												//Pin E5 as High
		break;
		
		case STRB_USB:
		PORTE.OUTSET = PIN4_bm;												//Pin E4 as High
		PORTE.OUTSET = PIN5_bm;												//Pin E5 as High
		break;
	}
}


